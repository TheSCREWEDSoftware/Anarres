#!/usr/bin/env python3
"""Writes layouts for the .dbc files AzerothCore has no table for, from the record headers of a 3.3.5a client
decompilation. Only the layout (field names, types and order) is taken; it's checked against real .dbc files.

Usage: generate-client-definitions.py <decomp WoW/Source/DB/Rec folder> <clean dbc folder> <AC definitions.json> <out>
"""
import json
import os
import re
import struct
import sys

LOCALES = ["enUS", "enGB", "koKR", "frFR", "deDE", "enCN", "zhCN", "enTW", "zhTW", "esES", "esMX", "ruRU", "ptPT",
           "ptBR", "itIT", "Unk"]
TYPES = {"int32_t": "Int32", "uint32_t": "UInt32", "float": "Float", "const char*": "String", "int8_t": "SByte",
         "uint8_t": "Byte", "int16_t": "Int16", "uint16_t": "UInt16"}
SIZES = {"Int32": 4, "UInt32": 4, "Float": 4, "String": 4, "SByte": 1, "Byte": 1, "Int16": 2, "UInt16": 2}
MEMBER = re.compile(r"/\* [0-9A-F]+ \*/\s+(const char\*|[a-z0-9_]+)\s+(\w+)\s*(?:\[(\d+)\])?\s*;")


def pascal(name):
    name = re.sub(r"^m_", "", name)
    return name[:1].upper() + name[1:]


def main():
    rec_folder, dbc_folder, ac_file, out_file = sys.argv[1:5]
    known = {entry["File"].lower() for entry in json.load(open(ac_file))["Definitions"]}
    definitions = []
    for header in sorted(os.listdir(rec_folder)):
        if not header.endswith("Rec.h"):
            continue
        source = os.path.join(rec_folder, header[:-2] + ".cpp")
        if not os.path.exists(source):
            continue
        code = open(source, encoding="utf-8", errors="replace").read()
        found = re.search(r'"DBFilesClient\\\\(\w+\.dbc)"', code)
        if not found or found.group(1).lower() in known:
            continue
        file = found.group(1)
        localised = set(re.findall(r"uint32_t (\w+)Offset\[16\]", code))
        text = open(os.path.join(rec_folder, header), encoding="utf-8", errors="replace").read()
        generated = "s_generatedID = true" in text
        columns = []
        for kind, name, count in MEMBER.findall(text):
            if kind not in TYPES:
                columns = None
                break
            base = pascal(name)
            bare = re.sub(r"^m_", "", name)
            if kind == "const char*" and bare in localised:
                columns += [{"Name": base + "_Lang_" + locale, "Type": "String"} for locale in LOCALES]
                columns.append({"Name": base + "_Lang_Mask", "Type": "UInt32"})
            elif count:
                columns += [{"Name": base + "_" + str(i + 1), "Type": TYPES[kind]} for i in range(int(count))]
            else:
                columns.append({"Name": base, "Type": TYPES[kind]})
        if not columns:
            continue
        # A generated ID is the row number, not a field in the file; it's the record's last member
        if generated:
            columns = [column for column in columns if column["Name"] != "GeneratedID"]
        if columns and columns[0]["Name"] == "Id":
            columns[0]["Name"] = "ID"
        path = os.path.join(dbc_folder, file)
        if not os.path.exists(path) or os.path.getsize(path) < 20:
            continue
        _, _, fields, size, _ = struct.unpack("<4s4I", open(path, "rb").read(20))
        if len(columns) != fields or sum(SIZES[column["Type"]] for column in columns) != size:
            print("skipped", file, len(columns), fields, file=sys.stderr)
            continue
        definitions.append({"File": file, "Table": "", "IndexIsRowNumber": generated, "Columns": columns})
    output = {"Build": "3.3.5a (12340)",
              "Source": "Layouts of client-only files, generated by tools/generate-client-definitions.py",
              "Definitions": definitions}
    with open(out_file, "w", newline="\n") as stream:
        json.dump(output, stream, indent=2)
        stream.write("\n")
    print(len(definitions), "definitions", file=sys.stderr)


if __name__ == "__main__":
    main()
